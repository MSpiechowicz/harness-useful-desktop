//! Saved harness sessions on disk (`sessions_list`, `session_tree`, `session_messages`,
//! `session_files_touched`).
//!
//! Sessions are addressed by an opaque [`SessionRef`]; the business layer resolves it inside the
//! harness's sessions directory for the project, so no session file path ever reaches the webview.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use super::{ChatMessage, SessionRef};

/// Maximum number of messages in one `session_messages` page.
pub const MAX_SESSION_PAGE: u32 = 200;

/// Maximum number of nodes in a [`SessionTree`]; larger sessions are cut and marked `truncated`.
pub const MAX_TREE_NODES: usize = 20_000;

/// Maximum length of [`SessionSummary::first_prompt`] in characters.
pub const MAX_FIRST_PROMPT_CHARS: usize = 160;

/// Maximum length of [`SessionNode::preview`] in characters.
pub const MAX_NODE_PREVIEW_CHARS: usize = 200;

/// Who set a session title.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum SessionTitleSource {
    /// Generated by the harness.
    Auto,
    /// Set by the user (OMP rename, PI `/name`).
    User,
}

/// One saved session in `sessions_list` (newest first).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct SessionSummary {
    /// Opaque reference used by every other session command and by `agent_start` `resume`.
    #[serde(rename = "ref")]
    pub session: SessionRef,
    /// Session title (OMP title slot, PI `session_info` name).
    pub title: Option<String>,
    /// Who set `title`, when the harness records it.
    pub title_source: Option<SessionTitleSource>,
    /// Working directory recorded in the session header.
    pub cwd: String,
    /// Creation time from the session header (RFC 3339).
    pub created_at: String,
    /// Last modification time of the session file (RFC 3339).
    pub updated_at: String,
    /// Size of the session file in bytes.
    #[ts(type = "number")]
    pub size_bytes: u64,
    /// Id of the last model used in the session (e.g. `claude-sonnet-4-5`).
    pub model: Option<String>,
    /// The first user prompt, at most [`MAX_FIRST_PROMPT_CHARS`] characters; the fallback title.
    pub first_prompt: Option<String>,
    /// Id of the session this one was forked from, when recorded in the header.
    pub parent_session: Option<String>,
}

/// What a session entry is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub enum SessionNodeKind {
    /// A user prompt.
    User,
    /// A model reply.
    Assistant,
    /// The result of a tool call.
    ToolResult,
    /// A `!command` run by the user.
    Bash,
    /// Context compaction.
    Compaction,
    /// Summary of an abandoned branch.
    BranchSummary,
    /// A label attached to an entry.
    Label,
    /// The model was switched.
    ModelChange,
    /// Any other entry type.
    Other,
}

/// One entry of a session's branch tree.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct SessionNode {
    /// Session entry id (the `entryId` of `fork`).
    pub id: String,
    /// Parent entry id; `None` for a root.
    pub parent_id: Option<String>,
    /// What the entry is.
    pub kind: SessionNodeKind,
    /// Text preview of user and assistant messages, at most [`MAX_NODE_PREVIEW_CHARS`] characters.
    pub preview: Option<String>,
    /// Entry time (RFC 3339), when recorded.
    pub timestamp: Option<String>,
    /// User label attached to the entry.
    pub label: Option<String>,
    /// True when the entry lies on the path from the root to the current leaf.
    pub on_active_path: bool,
    /// Number of direct children; more than one marks a branch point.
    pub child_count: u32,
}

/// Result of `session_tree`: every entry of a session with the active path marked.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct SessionTree {
    /// The session.
    #[serde(rename = "ref")]
    pub session: SessionRef,
    /// Entries in file order (parents before children).
    pub nodes: Vec<SessionNode>,
    /// The current leaf: the last appended message entry.
    pub leaf_id: Option<String>,
    /// Number of branch points (nodes with more than one child).
    pub branch_count: u32,
    /// True when the session has more than [`MAX_TREE_NODES`] entries and `nodes` was cut.
    pub truncated: bool,
}

/// Result of `session_messages`: one page of the read-only transcript of the active path
/// (root to leaf), read from the session file.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct SessionMessagesPage {
    /// Messages in transcript order.
    pub messages: Vec<ChatMessage>,
    /// Opaque cursor of the next page; `None` on the last page.
    pub next_cursor: Option<String>,
    /// Number of messages on the active path.
    pub total: u32,
}
